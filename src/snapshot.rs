//! `rosdistro_snapshot.yaml`: every release of a distribution (or one package and
//! its dependencies) pinned with its direct ROS dependencies, so that recipes are
//! generated from fixed releases and without walking rosdistro again.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use anyhow::{Context, Result};
use pixi_build_ros::package_xml::PackageXml;
use rayon::prelude::*;
use serde::Serialize;

use crate::distro::{Rosdistro, client};

/// Keys in the order vinca-snapshot (PyYAML, sorted) wrote them.
#[derive(Serialize)]
struct Entry {
    dependencies: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    repository: Option<String>,
    tag: String,
    url: String,
    version: String,
}

fn is_release_repo(url: &str) -> bool {
    let base = url
        .trim_end_matches('/')
        .rsplit('/')
        .next()
        .unwrap_or_default()
        .to_lowercase();
    let base = base.strip_suffix(".git").unwrap_or(&base);
    base.ends_with("-release") || base.ends_with("_release")
}

/// The direct dependencies of a package that are released in the distribution:
/// every dependency type (`depend` included), conditions evaluated.
fn direct_depends(xml: &PackageXml, rd: &Rosdistro) -> BTreeSet<String> {
    direct_depends_in(xml, &|n| rd.releases.contains_key(n))
}

fn direct_depends_in(xml: &PackageXml, released: &dyn Fn(&str) -> bool) -> BTreeSet<String> {
    let d = &xml.dependencies;
    [
        &d.buildtool_depends,
        &d.buildtool_export_depends,
        &d.build_depends,
        &d.build_export_depends,
        &d.run_depends,
        &d.test_depends,
        &d.exec_depends,
        &d.depend,
    ]
    .into_iter()
    .flatten()
    .filter(|dep| dep.is_active() && released(&dep.name))
    .map(|dep| dep.name.clone())
    .collect()
}

pub fn write(distro: &str, rosdistro_ref: Option<&str>, package: Option<&str>, out: &Path) -> Result<()> {
    let client = client()?;
    let rd = Rosdistro::load(&client, distro, rosdistro_ref)?;
    let env = rd.condition_env(distro);
    let parse = |pkg: &str| -> Result<PackageXml> {
        let xml = rd.package_xml(&client, pkg)?;
        Ok(PackageXml::parse(&xml)
            .map_err(|e| anyhow::anyhow!("{pkg}: {e}"))?
            .evaluate_conditions(&env))
    };

    let mut names: BTreeSet<String> = rd.releases.keys().cloned().collect();
    if let Some(root) = package {
        // the package and its dependencies, transitively
        let mut todo = vec![root.to_string()];
        names = BTreeSet::new();
        while let Some(p) = todo.pop() {
            if names.insert(p.clone()) {
                todo.extend(direct_depends(&parse(&p)?, &rd));
            }
        }
    }
    let entries: Vec<(String, Result<Entry>)> = names
        .into_par_iter()
        .map(|pkg| {
            let entry = (|| {
                let rel = &rd.releases[&pkg];
                let xml = parse(&pkg)?;
                Ok(Entry {
                    dependencies: direct_depends(&xml, &rd).into_iter().collect(),
                    repository: rel
                        .source_url
                        .as_deref()
                        .filter(|u| !is_release_repo(u))
                        .map(|u| u.strip_suffix(".git").unwrap_or(u).to_string()),
                    tag: rel.tag.clone(),
                    url: rel.url.clone(),
                    version: rel.version.clone(),
                })
            })();
            (pkg, entry)
        })
        .collect();
    let mut snapshot = BTreeMap::new();
    for (pkg, entry) in entries {
        match entry {
            Ok(e) => {
                snapshot.insert(pkg, e);
            }
            // e.g. a release repository that was removed: no package.xml to read
            Err(e) => eprintln!("warning: skipping {pkg}: {e:#}"),
        }
    }
    let at = rosdistro_ref
        .map(|r| format!(" at rosdistro {r}"))
        .unwrap_or_default();
    let header = format!(
        "# Snapshot generated by vinca-rs {} for distro {distro}{at}\n",
        env!("CARGO_PKG_VERSION")
    );
    std::fs::write(out, header + &serde_yaml::to_string(&snapshot)?)
        .with_context(|| out.display().to_string())?;
    eprintln!("{} packages written to {}", snapshot.len(), out.display());
    Ok(())
}

/// Add the dependencies to the entries of an existing snapshot that have none
/// (written before vinca-snapshot recorded them), from the package.xml of each
/// entry's pinned release; versions and everything else stay as they are.
pub fn fill_dependencies(distro: &str, path: &Path) -> Result<()> {
    use serde_yaml::{Mapping, Value};
    let client = client()?;
    let rd = Rosdistro::load(&client, distro, None)?;
    let env = rd.condition_env(distro);
    let text = std::fs::read_to_string(path).with_context(|| path.display().to_string())?;
    let header: String = text
        .lines()
        .take_while(|l| l.starts_with('#'))
        .map(|l| format!("{l}\n"))
        .collect();
    let mut snapshot: Mapping = serde_yaml::from_str(&text)?;
    let names: BTreeSet<String> = snapshot
        .keys()
        .filter_map(|k| k.as_str().map(String::from))
        .collect();
    let released = |n: &str| names.contains(n) || rd.releases.contains_key(n);
    let missing: Vec<(String, crate::config::SnapshotEntry)> = snapshot
        .iter()
        .filter(|(_, v)| v.get("dependencies").is_none())
        .map(|(k, v)| {
            Ok((
                k.as_str().unwrap_or_default().to_string(),
                serde_yaml::from_value(v.clone())?,
            ))
        })
        .collect::<Result<_>>()?;
    let filled: Vec<(String, Result<Vec<String>>)> = missing
        .into_par_iter()
        .map(|(pkg, entry)| {
            let deps = (|| {
                let url = crate::distro::Distro::raw_url(&entry)?;
                let xml = client.get(&url).send()?.error_for_status()?.text()?;
                let xml = PackageXml::parse(&xml)
                    .map_err(|e| anyhow::anyhow!("{pkg}: {e}"))?
                    .evaluate_conditions(&env);
                Ok(direct_depends_in(&xml, &released).into_iter().collect())
            })();
            (pkg, deps)
        })
        .collect();
    let mut n = 0;
    for (pkg, deps) in filled {
        let deps = deps.with_context(|| format!("{pkg}: reading its package.xml"))?;
        let entry = snapshot
            .get_mut(pkg.as_str())
            .and_then(Value::as_mapping_mut)
            .unwrap();
        let mut with = Mapping::new();
        with.insert(
            "dependencies".into(),
            Value::Sequence(deps.into_iter().map(Value::String).collect()),
        );
        with.extend(std::mem::take(entry));
        *entry = with;
        n += 1;
    }
    std::fs::write(path, header + &serde_yaml::to_string(&snapshot)?)?;
    eprintln!("dependencies added to {n} entries of {}", path.display());
    Ok(())
}
